package com.todo.domain.todo.recommendation;

/**
 * 팀 기록의 상태에 따라 어떤 프롬프트를 쓸지(또는 아예 부르지 않을지) 가른다.
 *
 * <p>기준은 기록의 양이 아니라 <b>재료의 존재</b>다. 빈 데이터에 모델을 부르면 지어낸 추천이
 * 나오므로 재료가 전혀 없을 때만 호출을 막고, 투두가 하나라도 있으면 전체 분석으로 간다 —
 * 없는 신호는 요약에서 섹션째 빠지고, 프롬프트가 "근거 없으면 빈 배열"을 강제한다.
 */
public enum RecommendationMode {
    /** 투두 0개이고 팀 설명도 없음. 모델을 부르지 않는다. */
    NONE,
    /** 투두는 0개지만 팀 설명이 있음. 설명만 보고 첫 할 일(NEW)을 제안한다. */
    STARTER,
    /** 투두가 1개 이상. 진행 중뿐이어도 부하·미배정 분석은 가능하다. */
    FULL
}
